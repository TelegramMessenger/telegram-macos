func installTelegramThemeHooks() {
    TelegramThemeHooks.install(TelegramThemeHooks(image: themeHookImage, icons: { palette, bubbled in
        return generateIcons(from: palette, bubbled: bubbled)
    }, sendingFrame: { color in
        return generateSendingFrame(color)
    }, clockMinImage: { color in
        return generateClockMinImage(color)
    }, chatGroupToggleSelected: { foregroundColor, backgroundColor in
        return generateChatGroupToggleSelected(foregroundColor: foregroundColor, backgroundColor: backgroundColor)
    }, chatGroupToggleUnselected: { foregroundColor, backgroundColor in
        return generateChatGroupToggleUnselected(foregroundColor: foregroundColor, backgroundColor: backgroundColor)
    }, setDefaultTheme: { window in
        setDefaultTheme(for: window)
    }, liteMode: {
        #if !SHARE
        if let value = appDelegate?.sharedApplicationContextValue?.sharedContext.baseSettings.liteMode {
            return value
        }
        #endif
        return .standart
    }, purgeLottieCache: {
        RLottieBridge.purgeModelCache()
    }, darkAppearance: {
        #if !SHARE
        return darkAppearance
        #else
        return theme
        #endif
    }, liveStreamBadgeColor: {
        return AvatarStoryIndicatorComponent.ActiveColors.default.stream[0]
    }))
    installTelegramUtilsHooks()
}
